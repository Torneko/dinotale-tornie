    // Only defined on Linux (see CMakeLists.txt) -- Windows uses plume's
    // D3D12 backend instead, which doesn't need an SDL window flag (it
    // talks to the GPU through the raw HWND returned below).
    flags |= SDL_WINDOW_VULKAN;
